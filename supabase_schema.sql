create table if not exists public.transacciones (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id) on delete cascade,
    descripcion text not null,
    monto numeric(12, 2) not null check (monto > 0),
    fecha date not null,
    categoria text not null,
    tipo text not null check (tipo in ('Ingreso', 'Gasto')),
    created_at timestamptz not null default now()
);

create index if not exists transacciones_user_fecha_idx
    on public.transacciones (user_id, fecha);

alter table public.transacciones enable row level security;

drop policy if exists "Cada usuario puede leer sus transacciones"
    on public.transacciones;
create policy "Cada usuario puede leer sus transacciones"
    on public.transacciones for select to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Cada usuario puede agregar sus transacciones"
    on public.transacciones;
create policy "Cada usuario puede agregar sus transacciones"
    on public.transacciones for insert to authenticated
    with check ((select auth.uid()) = user_id);

drop policy if exists "Cada usuario puede borrar sus transacciones"
    on public.transacciones;
create policy "Cada usuario puede borrar sus transacciones"
    on public.transacciones for delete to authenticated
    using ((select auth.uid()) = user_id);

grant select, insert, delete on public.transacciones to authenticated;
grant usage, select on sequence public.transacciones_id_seq to authenticated;
